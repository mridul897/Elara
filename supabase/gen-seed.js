// Generates 02-seed-1..4.sql from assets/products.js. Run: node supabase/gen-seed.js
const fs = require('fs'), path = require('path');
global.window = {};
require(path.join(__dirname, '..', 'assets', 'products.js'));
const P = window.ELARA_PRODUCTS;
const q = (s) => s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'";
const j = (o) => q(JSON.stringify(o)) + '::jsonb';
const arr = (a) => a && a.length ? "array[" + a.map(q).join(',') + "]" : "'{}'";
const parts = []; let out = null;
P.forEach((p, i) => {
  if (i % 15 === 0) { out = ['-- Generated by supabase/gen-seed.js from assets/products.js. Safe to re-run. Part ' + (parts.length + 1), 'begin;']; parts.push(out); }
  const regular = p.was || p.price;                 // storefront "was" = the regular price when a sale is on
  const sale = p.was ? p.price : null;
  const extra = {}; if (p.nafisa) extra.nafisa = p.nafisa; if (p.single) extra.single = p.single;
  out.push(`insert into public.products (id,name,cat,eyebrow,crumb,price,sale_price,badge,rating,reviews_count,description,dims,fits,care,ship,legacy,extra,position) values (` +
    [q(p.id), q(p.name), q(p.cat), q(p.eyebrow), q(p.crumb), regular, sale == null ? 'null' : sale, q(p.badge), p.rating || 0, p.reviews || 0,
     q(p.desc), p.dims ? `array[${p.dims.join(',')}]` : 'null', q(p.fits), q(p.care), q(p.ship), arr(p.legacy), j(extra), i].join(',') +
    `) on conflict (id) do update set name=excluded.name, cat=excluded.cat, price=excluded.price, sale_price=excluded.sale_price, badge=excluded.badge;`);
  p.colours.forEach((c, k) => {
    out.push(`insert into public.product_colours (product_id,id,label,hex,card,tile,guide_bg,photos,slides,position) values (` +
      [q(p.id), q(c.id), q(c.label), q(c.hex), q(c.card), q(c.tile), q(c.guideBg), j(c.photos || []), j(c.slides || []), k].join(',') +
      `) on conflict (product_id,id) do nothing;`);
    ['Small', 'Medium', 'Large'].forEach((s) => {
      out.push(`insert into public.product_variants (product_id,colour_id,size,stock) values (${q(p.id)},${q(c.id)},${q(s)},${s === 'Large' ? 0 : 8}) on conflict do nothing;`);
    });
  });
});
parts.forEach((o, n) => {
  o.push('commit;');
  fs.writeFileSync(path.join(__dirname, '02-seed-' + (n + 1) + '.sql'), o.join(String.fromCharCode(10)) + String.fromCharCode(10));
});
console.log('products', P.length, 'parts', parts.length);
